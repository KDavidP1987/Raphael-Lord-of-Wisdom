"""Regenerate Raphael/Resources/UnitCatalog.Data.cs from a unit_index.tsv dump.

The TSV (guid, name, faction, level, vblood, minion, health_settings) lives in the Nyarlathotep and
Beelzebub workspaces as local reference data. Usage:

    python tools/gen-unit-catalog.py "<path to unit_index.tsv>"
"""
import csv
import os
import sys

SKIP_FACTIONS = {"Faction_Players", "Faction_Ignored", "Faction_Critters", ""}
SKIP_NAME_PARTS = ("_Dummy", "_Test", "Tutorial", "_Illusion")


def main(src: str) -> None:
    rows = []
    with open(src, encoding="utf-8") as f:
        for x in csv.DictReader(f, delimiter="\t"):
            name, fac = x["name"].strip(), x["faction"].strip()
            if not name.startswith("CHAR_") or fac in SKIP_FACTIONS:
                continue
            if any(k in name for k in SKIP_NAME_PARTS):
                continue
            rows.append((name, fac.replace("Faction_", ""), int(x["level"] or 0),
                         x["vblood"].strip() == "Y", x["minion"].strip() == "Y"))
    rows.sort()

    b = lambda v: "true" if v else "false"
    out = [
        "// <auto-generated> by tools/gen-unit-catalog.py from a unit_index.tsv dump of the game's unit prefabs.",
        "// Player, critter and 'ignored' factions are left out. </auto-generated>",
        "namespace Raphael.Resources;",
        "",
        "internal static partial class UnitCatalog",
        "{",
        "    // (prefab name, faction without the Faction_ prefix, level, V Blood, minion)",
        "    internal static readonly (string Name, string Faction, int Level, bool VBlood, bool Minion)[] All =",
        "    {",
    ]
    out += [f'        ("{n}", "{fac}", {lvl}, {b(vb)}, {b(mn)}),' for n, fac, lvl, vb, mn in rows]
    out += ["    };", "}", ""]

    dst = os.path.join(os.path.dirname(__file__), "..", "Raphael", "Resources", "UnitCatalog.Data.cs")
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"{len(rows)} units ({sum(1 for r in rows if r[3])} V Blood) -> {os.path.normpath(dst)}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
